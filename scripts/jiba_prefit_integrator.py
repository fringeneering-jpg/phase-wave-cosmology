def fetch_horizons_vector(body_id, start_time="2004-09-01", stop_time="2004-09-02"):
    """Fetches exact un-fitted state vectors from JPL Horizons for Epoch 0"""
    url = (f"https://ssd.jpl.nasa.gov/api/horizons.api?format=json"
           f"&COMMAND='{body_id}'&OBJ_DATA='YES'&MAKE_EPHEM='YES'"
           f"&EPHEM_TYPE='VECTORS'&CENTER='500@10'&START_TIME='{start_time}'"
           f"&STOP_TIME='{stop_time}'&STEP_SIZE='1d'&OUT_UNITS='KM-S'")
    req = urllib.request.Request(url, headers={"User-Agent": "PWC-Integrator"})
    with urllib.request.urlopen(req, timeout=30) as response:
        data = json.loads(response.read().decode('utf-8'))
        lines = data['result'].split('$$SOE')[1].split('$$EOE')[0].strip().split('\n')
        # Parse X, Y, Z, VX, VY, VZ (convert km to meters)
        parts = lines[1].split(',')
        vec = [float(parts[2])*1000, float(parts[3])*1000, float(parts[4])*1000, 
               float(parts[5])*1000, float(parts[6])*1000, float(parts[7])*1000]
        return np.array(vec)

